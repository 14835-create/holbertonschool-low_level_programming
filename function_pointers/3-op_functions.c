#include "3-calc.h"

/**
 * op_add - returns sum of two numbers
 * @a: first num
 * @b: second num
 *
 * Return: sum of a + b
 */

int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - returns the difference of two numbers
 * @a: first num
 * @b: second num
 *
 * Return: difference of a and b
 */

int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - returns the product of two nums
 * @a: first num
 * @b: second num
 *
 * Return: product of a and b
 */

int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - returns division of two nums
 * @a: first num
 * @b: second num
 *
 * Return: the div of a and b
 */

int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - returns remainder dividing
 * @a: first num
 * @b: second num
 *
 * Return: remainder div of a and b
 */

int op_mod(int a, int b)
{
	return (a % b);
}
